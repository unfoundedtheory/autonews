-- Unfounded Theory: isolated first migration (PostgreSQL / Supabase).
-- Apply ONLY to a dedicated unfounded-theory project, never ORDAL-Web.
-- Public schema tables have RLS enabled and no public or authenticated policies.
-- Server connects with its own restricted Postgres connection, never exposes credentials.
BEGIN;

CREATE TABLE IF NOT EXISTS public.stories (
    id varchar(36) PRIMARY KEY,
    fingerprint varchar(64) NOT NULL UNIQUE,
    title text NOT NULL,
    source_url text NOT NULL,
    source_name varchar(120) NOT NULL,
    published_at timestamptz,
    topic varchar(40) NOT NULL DEFAULT 'astronomy',
    verification_status varchar(32) NOT NULL DEFAULT 'needs_fact_check',
    evidence jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.drafts (
    id varchar(36) PRIMARY KEY,
    story_id varchar(36) NOT NULL UNIQUE REFERENCES public.stories(id),
    version integer NOT NULL DEFAULT 1,
    highlight text NOT NULL,
    caption text NOT NULL,
    hashtags jsonb NOT NULL DEFAULT '[]'::jsonb,
    image_url text,
    source_image_url text,
    source_image_path text,
    media_page_url text,
    image_license_url text,
    photo_candidates jsonb NOT NULL DEFAULT '[]'::jsonb,
    accent_words jsonb NOT NULL DEFAULT '[]'::jsonb,
    is_tragedy boolean NOT NULL DEFAULT false,
    image_local_path text,
    image_credit text,
    photo_license varchar(120),
    rights_reviewed boolean NOT NULL DEFAULT false,
    status varchar(30) NOT NULL DEFAULT 'pending_approval',
    approved_version integer,
    approved_by varchar(50),
    approved_at timestamptz,
    scheduled_at timestamptz,
    expires_at timestamptz,
    ig_container_id varchar(80),
    ig_media_id varchar(80),
    publish_state varchar(30) NOT NULL DEFAULT 'unpublished',
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.audit (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id varchar(36) NOT NULL,
    event varchar(80) NOT NULL,
    actor varchar(80) NOT NULL,
    detail jsonb DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.telegram_sessions (
    user_id varchar(50) PRIMARY KEY,
    draft_id varchar(36) NOT NULL,
    mode varchar(20) NOT NULL,
    version integer NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_unfounded_drafts_schedule
    ON public.drafts(status, publish_state, scheduled_at);
CREATE INDEX IF NOT EXISTS idx_unfounded_drafts_approval
    ON public.drafts(approved_at, created_at);
CREATE INDEX IF NOT EXISTS idx_unfounded_stories_created_at
    ON public.stories(created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_unfounded_drafts_ig_container
    ON public.drafts(ig_container_id) WHERE ig_container_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_unfounded_drafts_ig_media
    ON public.drafts(ig_media_id) WHERE ig_media_id IS NOT NULL;

ALTER TABLE public.stories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telegram_sessions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.stories, public.drafts, public.audit, public.telegram_sessions
    FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;

-- No RLS policies = no anonymous browser access.
-- Public-read storage is needed for Instagram's remote image ingestion.
-- Creation/update/deletion must be performed by server-side service-role only.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('unfounded-media','unfounded-media',true,15728640,ARRAY['image/jpeg'])
ON CONFLICT (id) DO NOTHING;

COMMIT;
